#!/usr/bin/env python3
"""list_public_api.py -- the public names of the user module mlxf, and the program that imports every one.

The names are read from the `public ::` statements of src/core/mlxf.f90 (continuations joined, comments
dropped), in the order the module declares them. test/consumer/mlxf_api_names.f90 is a program that imports
each of them with `use mlxf, only:`; scripts/check_install.sh compiles it against the installed module, so a
name removed from mlxf fails the check, and runs --check, so a name added to mlxf fails until the program is
regenerated in the same change.

usage: scripts/list_public_api.py [ROOT]            prints the names, one per line
       scripts/list_public_api.py [ROOT] --write    (re)writes test/consumer/mlxf_api_names.f90
       scripts/list_public_api.py [ROOT] --check    exit 1 when the program differs from what --write writes
exit status: 0, 1 (--check found a difference), 2 (no public name found). Python 3.7, standard library only.
"""
import os
import re
import sys

MODULE = os.path.join('src', 'core', 'mlxf.f90')
PROGRAM = os.path.join('test', 'consumer', 'mlxf_api_names.f90')
WIDTH = 120
PUBLIC = re.compile(r'^\s*public\s*::(.*)$', re.I)


def statements(text):
    """The free-form statements of text, continuation lines joined and comments dropped."""
    out, cur = [], ''
    for raw in text.splitlines():
        line = raw.split('!', 1)[0].rstrip()
        stripped = line.lstrip()
        if cur and stripped.startswith('&'):
            stripped = stripped[1:]
        if stripped.endswith('&'):
            cur += stripped[:-1]
            continue
        out.append(cur + stripped)
        cur = ''
    if cur:
        out.append(cur)
    return out


def public_names(root):
    with open(os.path.join(root, MODULE)) as f:
        text = f.read()
    names = []
    for stmt in statements(text):
        m = PUBLIC.match(stmt)
        if not m:
            continue
        for name in m.group(1).split(','):
            name = name.strip()
            if name and name.lower() not in (n.lower() for n in names):
                names.append(name)
    return names


def program(names):
    head = 'use mlxf, only: '
    lines, cur = [], head
    for i, name in enumerate(names):
        item = name + (', ' if i < len(names) - 1 else '')
        if len(cur) + len(item.rstrip()) + 1 > WIDTH:
            lines.append(cur.rstrip() + ' &')
            cur = ' ' * len(head) + item
        else:
            cur += item
    lines.append(cur.rstrip())
    return '\n'.join([
        '!@descr: imports every public name of mlxf; generated by scripts/list_public_api.py, never edited',
        '! scripts/check_install.sh compiles it against the installed module: a removed public name fails it.',
        'program mlxf_api_names',
    ] + lines + [
        'implicit none',
        "print '(A,I0)', 'mlxf public names: ', %d" % len(names),
        'end program mlxf_api_names',
        '',
    ])


def main(argv):
    args = [a for a in argv[1:] if not a.startswith('--')]
    flags = [a for a in argv[1:] if a.startswith('--')]
    root = args[0] if args else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    names = public_names(root)
    if not names:
        print('list_public_api: no public name in %s' % MODULE, file=sys.stderr)
        return 2
    target = os.path.join(root, PROGRAM)
    if '--write' in flags:
        with open(target, 'w') as f:
            f.write(program(names))
        print('list_public_api: wrote %s (%d names)' % (PROGRAM, len(names)))
    elif '--check' in flags:
        try:
            with open(target) as f:
                have = f.read()
        except OSError:
            have = ''
        if have != program(names):
            print('list_public_api: %s does not list the %d public names of %s; run '
                  'scripts/list_public_api.py --write' % (PROGRAM, len(names), MODULE), file=sys.stderr)
            return 1
        print('list_public_api: %s lists the %d public names' % (PROGRAM, len(names)))
    else:
        print('\n'.join(names))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
